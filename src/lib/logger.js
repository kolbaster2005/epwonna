// Единая точка логирования ошибок. В проде ничего не пишет в консоль
// (чтобы у обычных пользователей в devtools не копился шум от сетевых
// сбоев, истёкших сессий, RLS-отказов и т.п. — это штатные, уже
// обработанные ошибки, а не что-то, что должен видеть посетитель сайта);
// в деве ведёт себя как обычный console.error, так что ничего не
// теряется при локальной отладке.
export function logError(...args) {
  if (import.meta.env.DEV) {
    console.error(...args)
  }
}
