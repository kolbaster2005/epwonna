// «Совет дня» на pro-главной (ProDashboard.jsx). Выбирается по номеру
// дня, так что в течение суток совет один и тот же, а на следующий день
// меняется сам. Кнопка-стрелка в виджете листает дальше по списку.
export const dailyTips = [
  'Лучший способ предсказать будущее — создать его.',
  'Решай пробники на время: на экзамене таймер не будет ждать.',
  'После каждого пробника разбери ошибки — именно там прячутся лишние баллы.',
  'Лучше 30 минут каждый день, чем 5 часов раз в неделю.',
  'Учи слова в контексте: целая фраза запоминается лучше отдельного слова.',
  'Пиши сочинение, а потом перечитай его через час — ошибки станут заметнее.',
  'Не застревай на одном задании: отметь его и вернись в конце.',
  'Повторение — мать учения. Вернись к пробнику, который решил неделю назад.',
  'Высыпайся перед экзаменом — свежая голова стоит больше ночи зубрёжки.',
  'Маленький шаг каждый день приводит к большому результату.',
]

// Индекс совета «на сегодня» — номер дня с начала эпохи по локальному
// времени, по модулю длины списка.
export function todayTipIndex(date = new Date()) {
  const localDay = Math.floor((date.getTime() - date.getTimezoneOffset() * 60000) / 86400000)
  return localDay % dailyTips.length
}
